"""Rebuilds sections/e4_references.tex as a numbered list in order of first citation.

The chapter cites with \\cite{key} (printed as superscript numbers). Each APA
entry lives in source/references.tex as  \\bibitem{key} <APA text>  (any order).
This script reads the sections in book order, finds the order in which keys are
first cited, and writes the numbered reference list. Uncited entries are left out.

Run before compiling:  python source/number_references.py
"""
import re
from pathlib import Path

BOOK = Path(__file__).resolve().parent.parent
SECTIONS = BOOK / "sections"
ORDER = re.findall(r"\\input\{sections/(\w+)\}", (BOOK / "main.tex").read_text(encoding="utf-8"))


def entries():
    text = (BOOK / "source" / "references.tex").read_text(encoding="utf-8")
    text = re.sub(r"(?m)^%.*\n", "", text)
    out = {}
    for m in re.finditer(r"\\bibitem\{([^}]+)\}\s*(.*?)(?=\\bibitem\{|\Z)", text, flags=re.S):
        out[m.group(1)] = m.group(2).strip()
    return out


def cite_order():
    seen = []
    for name in ORDER:
        if name == "e4_references":
            continue
        tex = (SECTIONS / f"{name}.tex").read_text(encoding="utf-8")
        tex = re.sub(r"(?m)(?<!\\)%.*$", "", tex)
        for group in re.findall(r"\\cite(?:\[[^\]]*\])?\{([^}]+)\}", tex):
            for key in (k.strip() for k in group.split(",")):
                if key not in seen:
                    seen.append(key)
    return seen


def build():
    refs, order = entries(), cite_order()
    missing = [k for k in order if k not in refs]
    if missing:
        raise SystemExit(f"cited but not in references.tex: {missing}")
    unused = [k for k in refs if k not in order]
    if unused:
        print("not cited, left out of the list (still kept in references.tex):", ", ".join(unused))
    keys = order
    lines = [
        "% Generated by source/number_references.py from source/references.tex. Do not edit by hand.",
        "% Numbered in order of first citation (superscript numbers in the text).",
        "\\renewcommand{\\bibsection}{\\section*{References}\\addcontentsline{toc}{section}{References}}",
        "\\begingroup\\small\\RaggedRight",
        "\\begin{thebibliography}{99}\\setlength{\\itemsep}{2pt}",
    ]
    lines += [f"\\bibitem{{{k}}} {refs[k]}" for k in keys]
    lines += ["\\end{thebibliography}", "\\endgroup"]
    (SECTIONS / "e4_references.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(order)} references cited and listed")
    return keys


if __name__ == "__main__":
    build()
