"""Prepares the merged chapter for compiling.

1. Writes sections/e1_glossary.tex from every \\keyterm{term}{definition} in the
   chapter sections, in the order they appear, so the glossary always matches
   the definitions in the text.
2. Counts main-text words per section (boxes, figures, tables, captions, margin
   notes and headings excluded, as the team plan assumes) and writes
   word_count.md.

Run:  python build_book.py      then compile main.tex with XeLaTeX (latexmk).
"""
import re
from pathlib import Path

BOOK = Path(__file__).resolve().parent.parent
SECTIONS = BOOK / "sections"

CHAPTER = [  # file, label in report, owner
    ("s00_intro.tex", "Introduction", "Member 1"),
    ("s01_exchange_rate.tex", "1 What is an exchange rate?", "Member 1"),
    ("s02_forex_market.tex", "2 The foreign exchange market", "Member 1"),
    ("s03_bop.tex", "3 The balance of payments", "Member 1"),
    ("s04_demand_supply.tex", "4 Demand and supply", "Member 2"),
    ("s05_appreciation.tex", "5 Appreciation and depreciation", "Member 2"),
    ("s06_systems.tex", "6 Exchange rate systems", "Member 3"),
    ("s07_reserves.tex", "7 The RBI and India's reserves", "Member 3"),
    ("s08_real_ppp.tex", "8 Real exchange rates and PPP", "Member 3"),
    ("s09_what_moves.tex", "9 What moves the rupee?", "Member 4"),
    ("s10_why_matters.tex", "10 Why exchange rates matter", "Member 4"),
    ("s11_crises.tex", "11 Currency crises in South Asia", "Member 4"),
    ("s12_conclusion.tex", "Conclusion", "Member 1"),
]
BOXES = ("didyouknow", "workedexample", "exercise", "economistsfacts", "keypoints",
         "casestudy", "economistsdisagree", "figure", "table")


def balanced(text, start):
    """Return the index just past the {...} group that opens at text[start]."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("unbalanced braces")


def keyterms(text):
    out, pos = [], 0
    while (i := text.find("\\keyterm{", pos)) != -1:
        a_end = balanced(text, i + 8)
        b_end = balanced(text, a_end)
        out.append((text[i + 9:a_end - 1], text[a_end + 1:b_end - 1]))
        pos = b_end
    return out


def strip_command_with_args(text, name, nargs, keep=None):
    pos = 0
    while (i := text.find("\\" + name + "{", pos)) != -1:
        ends, j = [], i + len(name) + 1
        for _ in range(nargs):
            j = balanced(text, j)
            ends.append(j)
        starts = [i + len(name) + 1] + ends[:-1]
        kept = text[starts[keep] + 1:ends[keep] - 1] if keep is not None else ""
        text = text[:i] + kept + text[ends[-1]:]
        pos = i
    return text


def main_text_words(text):
    text = re.sub(r"(?m)(?<!\\)%.*$", "", text)
    for env in BOXES:
        text = re.sub(r"\\begin\{%s\}.*?\\end\{%s\}" % (env, env), " ", text, flags=re.S)
    text = strip_command_with_args(text, "keyterm", 2, keep=0)
    text = strip_command_with_args(text, "sidenote", 1)
    for cmd in ("section", "section*", "subsection", "label", "addcontentsline"):
        text = re.sub(r"\\%s(\{[^}]*\})+" % re.escape(cmd), " ", text)
    text = re.sub(r"\\seesec\{[^}]*\}", "(see Section 0)", text)
    text = re.sub(r"\\secref\{[^}]*\}", "Section 0", text)
    text = re.sub(r"\\minihead\{([^}]*)\}", r"\1", text)
    text = re.sub(r"\\[a-zA-Z]+\*?", " ", text)
    text = re.sub(r"[{}\[\]~\\]", " ", text)
    return len([w for w in text.split() if re.search(r"[\w₹$]", w)])


def build():
    terms, rows, totals = [], [], {}
    for fname, label, owner in CHAPTER:
        tex = (SECTIONS / fname).read_text(encoding="utf-8")
        terms += keyterms(tex)
        n = main_text_words(tex)
        rows.append((label, owner, n))
        totals[owner] = totals.get(owner, 0) + n

    lines = ["% Generated by source/build_book.py from the \\keyterm definitions. Do not edit by hand.",
             "\\section*{Glossary}", "\\addcontentsline{toc}{section}{Glossary}",
             "\\begingroup\\small\\setlength{\\parindent}{-1.5em}\\setlength{\\leftskip}{1.5em}\\RaggedRight"]
    # Glossary headwords are nouns in lower case, whatever form the text uses.
    rename = {"appreciates": "appreciation", "depreciated": "depreciation"}
    keep_caps = ("Special Drawing Rights",)
    terms = [(rename.get(t, t if t.startswith(keep_caps) else t[0].lower() + t[1:]), d)
             for t, d in terms]
    seen = set()
    for term, definition in sorted(terms, key=lambda t: t[0].lower()):
        key = term.lower()
        if key in seen:
            continue
        seen.add(key)
        lines.append(f"\\textbf{{{term}}}\\quad {definition}\\par\\smallskip")
    lines.append("\\endgroup")
    (SECTIONS / "e1_glossary.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(totals.values())
    report = ["# Word count: main text only", "",
              "Boxes, figures, tables, captions, margin notes, headings and end matter are excluded.",
              "Limit agreed: 5,000 words, with up to 10% over (5,500).", "",
              "| Section | Owner | Words |", "|---|---|---|"]
    report += [f"| {l} | {o} | {n} |" for l, o, n in rows]
    report += ["", "| Member | Words |", "|---|---|"]
    report += [f"| {o} | {n} |" for o, n in totals.items()]
    report += [f"| **Total** | **{total}** |", ""]
    (BOOK / "word_count.md").write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"Glossary: {len(seen)} terms")


if __name__ == "__main__":
    build()
